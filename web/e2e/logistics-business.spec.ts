import { expect, test } from '@playwright/test'

test('物流业务信息支持多选、单选，并保留在草稿和提交记录中', async ({ page }) => {
  await page.goto('/registration/logistics')
  await page.getByText('我已阅读并同意以上须知').click()
  await page.getByRole('button', { name: '确认并继续', exact: true }).click()
  await expect(page.getByRole('heading', { name: '物流业务信息', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(page.getByText('请选择入厂事由', { exact: true }).last()).toBeVisible()
  await expect(page.getByText('请选择货物类型', { exact: true }).last()).toBeVisible()
  await expect(page.getByText('请填写厂内对接人', { exact: true })).toBeVisible()
  await expect(page.getByText('请填写业务单号', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '选择入厂事由', exact: true }).click()
  for (const reason of ['送货', '提货', '退货', '退货']) await page.getByText(reason, { exact: true }).click()
  await page.getByRole('button', { name: '完成选择', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择入厂事由', exact: true })).toContainText('送货、提货')
  await page.getByRole('textbox', { name: '厂内对接人', exact: true }).fill('刘工')
  await page.getByRole('button', { name: '选择货物类型', exact: true }).click()
  await page.getByText('原材料', { exact: true }).click()
  await page.getByText('设备', { exact: true }).click()
  await page.getByRole('button', { name: '完成选择', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择货物类型', exact: true })).toHaveText('设备')
  await page.getByRole('textbox', { name: '业务单号', exact: true }).fill('WL-20261013-001')
  await page.reload()
  await expect(page.getByRole('button', { name: '选择入厂事由', exact: true })).toContainText('送货、提货')
  await expect(page.getByRole('button', { name: '选择货物类型', exact: true })).toHaveText('设备')
  await expect(page.getByRole('textbox', { name: '厂内对接人', exact: true })).toHaveValue('刘工')
  await expect(page.getByRole('textbox', { name: '业务单号', exact: true })).toHaveValue('WL-20261013-001')
  for (const width of [320, 390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/logistics-business-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: '填入预约与两条演示数据' }).click()
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await page.getByRole('button', { name: '非生产区', exact: true }).click()
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(page.getByText('送货、提货', { exact: true })).toBeVisible()
  await expect(page.getByText('WL-20261013-001', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '提交并开始培训' }).click()
  await expect(page.getByText('人员培训进度')).toBeVisible()
  await page.reload()
  const visit = await page.evaluate(() => JSON.parse(localStorage.getItem('visitsafe.web.v2')!).visits[0])
  expect(visit).toMatchObject({ logisticsReasons: ['送货', '提货'], logisticsContact: '刘工', cargoType: '设备', logisticsOrderNumber: 'WL-20261013-001' })
})
